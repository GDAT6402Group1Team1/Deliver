def story(number, topic, role, current, stats, opening, first, second, validation=False):
    return {'id': f'change-{number:03}', 'topic': topic, 'role': role, 'current_action': current,
            'received': stats[0], 'punches': stats[1], 'hits': stats[2], 'opening': opening,
            'branches': [first, second], 'usage': 'validation' if validation else 'train'}


